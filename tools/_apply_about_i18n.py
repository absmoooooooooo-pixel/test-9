LANGUAGE_CODES = ["en", "hi", "mr", "de", "es", "fr", "ja", "pt", "ar"]

for code in LANGUAGE_CODES:
    path = Path("frontend/i18n") / f"{code}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    values = T[code]
    missing = [key for key in SRC if key not in values]
    extra = [key for key in values if key not in SRC]
    if missing or extra:
        raise SystemExit(f"{code}: missing={missing} extra={extra}")

    strings = data.setdefault("strings", {})

    # This runtime indexes dictionaries by the exact English sentence shown
    # on the page. Remove the temporary semantic keys and store the real
    # source strings; English maps each source string to itself.
    for key in SRC:
        strings.pop(key, None)
    for key, source in SRC.items():
        strings[source] = values[key]

    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{code}: {len(SRC)} about/footer strings applied")
