#!/usr/bin/env python3
"""Prepare the one English website for in-place translation.

    python tools/build_i18n.py

There is no translated page tree. Every page is the English page. This script
loads the language dictionaries from frontend/i18n/<code>.json, writes them to
one shared frontend/i18n/translations.js file, and adds the same language
switcher and in-place translator to every English page.

The page's own text, calculator controls, formulas, IDs and links are never
rewritten. The browser runtime changes visible text only.
"""
from __future__ import annotations

import html as html_module
import json
import posixpath
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import i18n_paths as paths

PROJECT_ROOT = paths.PROJECT_ROOT
I18N_DIR = paths.I18N_DIR

SWITCHER_START = "<!-- I18N:SWITCHER (generated by tools/build_i18n.py) -->"
SWITCHER_END = "<!-- /I18N:SWITCHER -->"
ASSETS_START = "<!-- I18N:ASSETS (generated by tools/build_i18n.py) -->"
ASSETS_END = "<!-- /I18N:ASSETS -->"
RUNTIME_VERSION = "48"

GLOBE_SVG = (
    '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false" fill="none" '
    'stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round">'
    '<circle cx="12" cy="12" r="8.5"/><path d="M3.5 12h17"/>'
    '<path d="M12 3.5c2.4 2.4 3.6 5.3 3.6 8.5s-1.2 6.1-3.6 8.5c-2.4-2.4-3.6-5.3-3.6-8.5S9.6 5.9 12 3.5Z"/>'
    "</svg>"
)


def escape_html(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def page_heading(html: str) -> str:
    match = re.search(r"<h1[^>]*>(.*?)</h1>", html, re.S)
    if not match:
        return ""
    value = re.sub(r"<[^>]+>", "", match.group(1))
    return re.sub(r"\s+", " ", html_module.unescape(value)).strip()


def page_kind(relative: str) -> str:
    inner = paths.strip_frontend(relative)
    if inner == "index.html":
        return "home"
    if inner.startswith("about/"):
        return "about"
    return "calculator"


def strip_generated_blocks(html: str) -> str:
    html = re.sub(
        re.escape(SWITCHER_START) + r".*?" + re.escape(SWITCHER_END) + r"\n?",
        "",
        html,
        flags=re.S,
    )
    html = re.sub(
        re.escape(ASSETS_START) + r".*?" + re.escape(ASSETS_END) + r"\n?",
        "",
        html,
        flags=re.S,
    )
    return html


def insert_into_brand(html: str, block: str) -> str:
    start = html.find('<div class="brand">')
    if start == -1:
        return html

    depth = 0
    index = start
    while True:
        open_at = html.find("<div", index)
        close_at = html.find("</div>", index)
        if close_at == -1:
            return html
        if open_at != -1 and open_at < close_at:
            depth += 1
            index = open_at + 4
            continue
        depth -= 1
        index = close_at + 6
        if depth == 0:
            break

    return html[:close_at] + block + "\n    " + html[close_at:]


def switcher_markup() -> str:
    items = []
    for item in paths.load_languages()["languages"]:
        code = item["code"]
        flag = escape_html(item.get("flag", ""))
        native = escape_html(item["nativeName"])
        name = escape_html(item["name"])
        lang_dir = item.get("dir", "ltr")
        active = ' aria-current="true"' if code == "en" else ""
        items.append(
            f'            <li><a href="#" hreflang="{code}" lang="{code}" '
            f'dir="ltr" data-og-locale="{item.get("ogLocale", code)}" '
            f'data-short="{escape_html(item["short"])}" role="button" '
            f'title="{name}"{active}>'
            f'<span class="lang-switch__flag lang-switch__flag--{flag}" aria-hidden="true"></span>'
            f'<span class="lang-switch__name" lang="{code}" dir="{lang_dir}">{native}</span>'
            f"</a></li>"
        )

    return "\n".join(
        [
            SWITCHER_START,
            '        <details class="lang-switch" data-lang="en">',
            '            <summary aria-label="Change language" title="Change language">',
            f"                {GLOBE_SVG}",
            '                <span class="lang-switch__label">',
            '                    <span class="lang-switch__label-full" lang="en">English</span>',
            '                    <span class="lang-switch__label-short">ENG</span>',
            '                </span>',
            "            </summary>",
            '            <ul class="lang-switch__menu" role="list">',
            *items,
            "            </ul>",
            "        </details>",
            SWITCHER_END,
        ]
    )


def asset_block(output_relative: str, sources: dict) -> str:
    output_dir = posixpath.dirname(output_relative)

    def relative(path: str) -> str:
        return posixpath.relpath(path, output_dir or ".")

    css = relative("frontend/i18n/language-switcher.css") + f"?v={RUNTIME_VERSION}"
    number_format = relative("frontend/i18n/number-format.js") + f"?v={RUNTIME_VERSION}"
    translations = relative("frontend/i18n/translations.js") + f"?v={RUNTIME_VERSION}"
    translator = relative("frontend/i18n/i18n.js") + f"?v={RUNTIME_VERSION}"
    switcher = relative("frontend/i18n/language-switcher.js") + f"?v={RUNTIME_VERSION}"

    languages = [
        {
            "code": item["code"],
            "dir": item.get("dir", "ltr"),
            "ogLocale": item.get("ogLocale", item["code"]),
            "name": item["name"],
            "nativeName": item["nativeName"],
            "short": item["short"],
        }
        for item in paths.load_languages()["languages"]
    ]
    config_json = json.dumps(
        {"current": "en", "languages": languages},
        ensure_ascii=False,
        separators=(",", ":"),
    ).replace("</", "<\\/")
    source_json = json.dumps(sources, ensure_ascii=False, separators=(",", ":")).replace(
        "</", "<\\/"
    )

    return "\n".join(
        [
            ASSETS_START,
            f'    <link rel="stylesheet" href="{css}">',
            f"    <script>window.__MW_I18N_CONFIG={config_json};</script>",
            f'    <script type="application/json" id="mw-i18n-sources">{source_json}</script>',
            f'    <script src="{number_format}"></script>',
            f'    <script src="{translations}" defer></script>',
            f'    <script src="{translator}" defer></script>',
            f'    <script src="{switcher}" defer></script>',
            ASSETS_END,
        ]
    )


def write_shared_dictionary(languages: list[dict]) -> None:
    payload = {}
    for item in languages:
        code = item["code"]
        dictionary = paths.load_dictionary(code)
        payload[code] = {
            "code": code,
            "terms": dictionary.get("terms", {}),
            "strings": dictionary.get("strings", {}),
            "templates": dictionary.get("templates", {}),
        }

    text = (
        "window.MW_I18N_DICTIONARIES="
        + json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    (I18N_DIR / "translations.js").write_text(text, encoding="utf-8", newline="\n")


def build() -> None:
    languages = paths.load_languages()["languages"]
    write_shared_dictionary(languages)

    pages = paths.source_pages()
    for relative in pages:
        page = PROJECT_ROOT / relative
        source = page.read_text(encoding="utf-8")
        html = strip_generated_blocks(source)
        heading = page_heading(html)
        sources = {
            "text": {},
            "attrs": {},
            "kind": page_kind(relative),
            "h1": heading,
        }

        html = re.sub(
            r"<html\b[^>]*>",
            f'<html lang="en" dir="ltr" data-mw-page="{sources["kind"]}">',
            html,
            count=1,
        )
        html = insert_into_brand(html, switcher_markup())
        html = html.replace("</head>", asset_block(relative, sources) + "\n</head>", 1)

        page.write_text(html, encoding="utf-8", newline="\n")

    print(f"pages prepared: {len(pages)}")
    print(f"shared dictionary: {(I18N_DIR / 'translations.js').relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    build()
